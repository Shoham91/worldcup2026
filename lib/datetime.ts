// Calendar day of a Date in tournament local time (Asia/Jerusalem) as
// "YYYY-MM-DD" — sortable and comparable with plain string operators.
export function jerusalemDay(d: Date): string {
  return new Intl.DateTimeFormat("en-CA", {
    timeZone: "Asia/Jerusalem",
    year: "numeric",
    month: "2-digit",
    day: "2-digit",
  }).format(d);
}

// Format a Date as the value a <input type="datetime-local"> expects,
// using local time components.
export function toLocalInput(d: Date | null | undefined): string {
  if (!d) return "";
  const pad = (n: number) => String(n).padStart(2, "0");
  return `${d.getFullYear()}-${pad(d.getMonth() + 1)}-${pad(d.getDate())}T${pad(
    d.getHours(),
  )}:${pad(d.getMinutes())}`;
}
